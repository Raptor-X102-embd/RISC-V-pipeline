.text
.globl _start
_start:
    li   x1, 10 #00      # счетчик N = 10
    li   x2, 0  #04     # сумма = 0
loop:
    add  x2, x2, x1 #08  # sum += N
    addi x1, x1, -1 #0C  # N--
    bne  x1, x0, loop #10 # если N != 0, повторить

    # сохраняем результат в память (слово по адресу 0)
    sw   x2, 0(x0) #14

    # копируем результат в регистр x3 для проверки
    mv   x3, x2 #18

    # бесконечный цикл (завершение)
    nop #1C
    nop
    nop
    nop
    nop
