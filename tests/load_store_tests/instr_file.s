.text
.globl _start
_start:
    # Проверка LUI
    lui x1, 0x12345         # x1 = 0x12345000

    # Проверка AUIPC (получим PC + 0x6789000, но точное значение зависит от адреса,
    # поэтому мы не будем проверять x2, а используем его только для демонстрации)
    auipc x2, 0x6789        # x2 = PC + 0x6789000

    # Запись начальных данных в память (адреса 32, 36, 40)
    addi x3, x0, 0xAA       # x3 = 170
    sw   x3, 32(x0)         # mem[32] = 0xAA
    addi x4, x0, 0xBB       # x4 = 187
    sw   x4, 36(x0)         # mem[36] = 0xBB
    addi x5, x0, 0xCC       # x5 = 204
    sw   x5, 40(x0)         # mem[40] = 0xCC

    # Проверка LOAD: LW, LH, LB, LBU, LHU
    lw   x6, 32(x0)         # x6 = 0x000000AA
    lh   x7, 36(x0)         # x7 = 0x000000BB (полуслово 0x00BB, знак +)
    lb   x8, 40(x0)         # x8 = 0xFFFFFFCC (байт 0xCC, знак -)
    lbu  x9, 40(x0)         # x9 = 0x000000CC
    lhu  x10, 36(x0)        # x10 = 0x000000BB

    # Арифметика с регистрами и immediate
    addi x11, x0, 5
    addi x12, x0, 3
    add  x13, x11, x12      # 8
    sub  x14, x11, x12      # 2
    and  x15, x11, x12      # 1
    or   x16, x11, x12      # 7
    xor  x17, x11, x12      # 6
    sll  x18, x11, x12      # 5 << 3 = 40
    srl  x19, x11, x12      # 5 >> 3 = 0 (логический)
    sra  x20, x11, x12      # 5 >> 3 = 0 (арифм. для положительного то же)
    slt  x21, x11, x12      # 5 < 3 ? 0
    sltu x22, x11, x12      # 0 (беззнаковое сравнение)

    # (Опционально) сохраним результаты в память для дополнительной проверки,
    # но проще проверить регистры через expect.txt

exit:
    nop
