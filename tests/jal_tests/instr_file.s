.text
.globl _start
_start:
    # JAL: переходим вперёд, записываем адрес возврата (следующей инструкции) в x1
    jal  x1, forward_target          # x1 = 0x4
    addi x2, x0, 1                   # не выполняется (пропускается)

forward_target:
    addi x2, x0, 100                 # x2 = 100

    # JALR: прыгаем на адрес (x1 + 16), чтобы попасть на инструкцию addi x5...
    # x1 = 0x4, 0x4 + 16 = 0x14 – это адрес addi x5, x0, 200
    addi x3, x1, 16                  # x3 = 0x14
    jalr x4, x3, 0                   # переход на 0x14, x4 = PC+4 = 0x14 (адрес следующей инструкции)

    # сюда попадаем после jalr
    addi x5, x0, 200                 # x5 = 200
    jal  exit

    # сюда не должны попасть
    .align 2
    addi x6, x0, 300                 # не выполняется

exit:
    sw   x4, 4(x0)                   # память[4] = 0x14 (адрес возврата)
    sw   x2, 0(x0)                   # память[0] = 100
    sw   x5, 8(x0)                   # память[8] = 200
    nop
